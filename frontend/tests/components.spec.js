import { expect, test } from '@playwright/test'
test('dashboard renders locally and opens approved rather than requested conditions', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Добрый день, Александр' })).toBeVisible()
  await page.getByRole('button', { name: 'Открыть заявку №1041' }).click()
  await expect(page.getByRole('heading', { name: 'Одобренные условия' })).toBeVisible()
  await expect(page.locator('.offer-summary__amount')).toContainText('800')
  await expect(page.getByRole('button', { name: 'Подписать и получить' })).toBeVisible()
  expect(errors).toEqual([])
})
test('application form validates amount and permits an incomplete draft', async ({ page }) => {
  await page.goto('/?view=application')
  await page.getByLabel('Сумма кредита', { exact: true }).fill('10')
  await page.getByRole('button', { name: 'Отправить заявку' }).click()
  await expect(page.getByLabel('Сумма кредита', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Сумма кредита', { exact: true }).fill('')
  await page.getByRole('button', { name: 'Сохранить черновик' }).click()
  await expect(page.getByRole('status')).toContainText('сохранение черновика')
  await page.getByLabel('Сумма кредита', { exact: true }).fill('1 500 000,50')
  await page.getByRole('button', { name: 'Отправить заявку' }).click()
  await expect(page.getByRole('status')).toContainText('1500000.50')
})
test('technical review exposes only server-authorized retry and search works', async ({ page }) => {
  await page.goto('/?view=employee')
  await page.getByRole('button', { name: 'ООО АльфаТех' }).click()
  await expect(page.getByRole('button', { name: 'Повторить проверки' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Одобрить', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Повторить проверки' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Демонстрация:' })).toContainText('повтор проверок')
  await page.getByRole('searchbox').fill('Несуществующая')
  await expect(page.getByRole('heading', { name: 'Заявок не найдено' })).toBeVisible()
})
test('employee action dialog validates required explanation and closes with Escape', async ({ page }) => {
  await page.goto('/?view=employee')
  await page.getByRole('button', { name: 'Одобрить', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Одобрить', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Добавьте комментарий')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
})
test('tabs support keyboard navigation', async ({ page }) => {
  await page.goto('/?view=components')
  const first = page.getByRole('tab', { name: 'Общая информация', exact: true })
  await first.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'История', exact: true })).toBeFocused()
  await expect(page.getByRole('tabpanel').filter({ visible: true })).toContainText('Содержимое второй вкладки')
})
test('screens have no page-level horizontal overflow at mobile width', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  for (const view of ['dashboard', 'application', 'employee', 'components']) {
    await page.goto('/?view=' + view)
    await expect(page.getByRole('main')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
})
