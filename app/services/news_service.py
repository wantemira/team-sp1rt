from fastapi import HTTPException
from sqlalchemy.orm import Session

from app.models import User
from app.repositories import application_repository
from app.schemas.news import NewsItem


def get_client_news(db: Session, user: User) -> list[NewsItem]:
    client = user.client_profile
    if client is None:
        raise HTTPException(status_code=500, detail="У клиента отсутствует профиль бизнеса.")
    application = application_repository.get_latest_client_application(db, client.id)
    status = application.status if application is not None else None
    articles = {
        None: (
            "start", "Как подготовить заявку на оборотный кредит",
            "Выберите сумму и срок; сведения о бизнесе уже есть в профиле.",
            "Создайте заявку на пополнение оборотных средств. Укажите сумму и срок. "
            "ИНН берётся из профиля бизнеса. После отправки система проверит сведения "
            "и предложит условия либо запросит недостающие данные.",
            "У вас пока нет заявок на кредит.",
        ),
        "DRAFT": (
            "draft", "Продолжите заполнение заявки",
            "Сохранённый черновик можно открыть и отправить на рассмотрение.",
            "Откройте черновик в разделе «Мои заявки», проверьте сумму и срок. "
            "Кнопка «Отправить заявку» запустит проверки и расчёт. "
            "Сохранение черновика само по себе не запускает рассмотрение.",
            "Ваша последняя заявка сохранена как черновик.",
        ),
        "CHECKING": (
            "checking", "Как проходят проверки бизнеса",
            "Результаты ФНС и БКИ сохраняются в истории заявки.",
            "Проверки подтверждают сведения о бизнесе и его обязательствах. "
            "Если источник недоступен, сотрудник может повторить запрос. "
            "Технический сбой сам по себе не означает кредитный отказ.",
            "Последняя заявка находится на проверке.",
        ),
        "NEEDS_INFO": (
            "information", "Дополните сведения для рассмотрения",
            "В карточке заявки перечислены показатели, которых не хватает.",
            "Откройте заявку и заполните только запрошенные финансовые поля. "
            "После отправки сведений система повторит проверки и расчёт. "
            "Результат и объяснение появятся в той же карточке.",
            "По вашей последней заявке запрошены дополнительные сведения.",
        ),
        "MANUAL_REVIEW": (
            "review", "Как сотрудник принимает кредитное решение",
            "Баллы рассматриваются вместе с денежным потоком и обязательствами.",
            "Сотрудник видит выручку, расходы, денежный поток, текущие платежи "
            "и дисциплину погашения. Он может одобрить безопасные условия, "
            "отказать с объяснением или запросить сведения. Действие сохраняется в истории.",
            "Последняя заявка передана сотруднику.",
        ),
        "APPROVED": (
            "approved", "Проверьте условия перед согласием",
            "Сравните сумму, срок, ставку и ежемесячный платёж.",
            "Условия сохранены в карточке заявки. Прочитайте объяснение решения "
            "и подтвердите согласие, если предложение вам подходит. "
            "В прототипе подписание и выдача смоделированы.",
            "По вашей последней заявке подготовлено предложение.",
        ),
        "ISSUED": (
            "issued", "Где посмотреть принятые условия",
            "Сумма, ставка и платёж доступны после подтверждения предложения.",
            "Откройте заявку в разделе «Мои заявки»: там сохранены принятые условия, "
            "время согласия и история рассмотрения. В этом прототипе выдача "
            "смоделирована, реальный перевод средств не выполняется.",
            "Вы приняли предложение по последней заявке.",
        ),
        "REJECTED": (
            "rejected", "Где найти объяснение отказа",
            "Причина решения и история проверок доступны в карточке заявки.",
            "Откройте отклонённую заявку и прочитайте причину решения. "
            "Стоп-факторы и недостаточный денежный поток учитываются отдельно "
            "от скорингового балла. История сохраняет результаты рассмотрения.",
            "По вашей последней заявке принято решение об отказе.",
        ),
    }
    article = articles.get(status, articles[None])
    if status == "MANUAL_REVIEW" and application.decision_reason_code in {
        "EXTERNAL_CHECK_UNAVAILABLE", "EXTERNAL_DATA_INCOMPLETE", "INVALID_SOURCE_DATA",
    }:
        article = (
            "retry", "Почему проверку источника нужно повторить",
            "Недоступные или неполные данные не подменяются кредитным отказом.",
            "Сотруднику доступен повтор проблемных проверок. После получения "
            "пригодных данных система продолжит обычное рассмотрение и при "
            "необходимости запросит недостающие финансовые показатели.",
            "Источники не дали пригодные данные по вашей последней заявке.",
        )
    if status == "APPROVED" and (application.offer or {}).get("kind") == "COUNTER_OFFER":
        article = (
            "counter-offer", "Почему предложенная сумма меньше запрошенной",
            "Система рассчитывает платёж, который покрывается денежным потоком бизнеса.",
            "Доступная сумма ограничивается отношением денежного потока к общим "
            "долговым платежам — DSCR. В этой модели итоговый DSCR должен быть "
            "не ниже 1,35. Посмотрите расчёт в карточке: уменьшенная сумма "
            "позволяет предложить безопасные условия вместо полного отказа.",
            "По вашей последней заявке рассчитано встречное предложение.",
        )
    key, title, excerpt, body, relevance = article
    individual = client.client_type == "INDIVIDUAL"
    return [
        NewsItem(id=f"application-{key}", title=title, excerpt=excerpt, body=body, relevance=relevance),
        NewsItem(
            id="profile-individual" if individual else "profile-company",
            title="Оборотный кредит для ИП" if individual else "Оборотный кредит для организации",
            excerpt="Какие сведения используются при рассмотрении заявки вашего бизнеса.",
            body=(
                "Для ИП используется ИНН из профиля и проверка сведений ЕГРИП. "
                if individual else
                "Для организации используется ИНН из профиля и проверка сведений ЕГРЮЛ. "
            ) + "В расчёте учитываются выручка, операционные расходы и платежи по кредитам. "
                "Сведения ФНС и БКИ на этом стенде синтетические.",
            relevance="Ваш профиль — индивидуальный предприниматель." if individual else "Ваш профиль — организация.",
        ),
    ]
